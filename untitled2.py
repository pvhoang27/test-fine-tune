import torch
import transformers

print("PyTorch:", torch.__version__)
print("Transformers:", transformers.__version__)
print("GPU:", torch.cuda.is_available())

device = "cuda" if torch.cuda.is_available() else "cpu"
print("Device:", device)

from datasets import load_dataset

# Sử dụng đường dẫn đầy đủ của dataset imdb trên Hugging Face
dataset = load_dataset("stanfordnlp/imdb")

print(dataset)

print("\nReview mẫu:")
print(dataset["train"][0]["text"][:300])

print("\nLabel:", dataset["train"][0]["label"])

# Lấy 50 mẫu Negative và 50 mẫu Positive
train_negative = (
    dataset["train"]
    .filter(lambda x: x["label"] == 0)
    .shuffle(seed=42)
    .select(range(50))
)

train_positive = (
    dataset["train"]
    .filter(lambda x: x["label"] == 1)
    .shuffle(seed=42)
    .select(range(50))
)

from datasets import concatenate_datasets

train_data = concatenate_datasets([
    train_negative,
    train_positive
]).shuffle(seed=42)

# 30 mẫu validation, cân bằng hai nhãn
test_negative = (
    dataset["test"]
    .filter(lambda x: x["label"] == 0)
    .shuffle(seed=42)
    .select(range(15))
)

test_positive = (
    dataset["test"]
    .filter(lambda x: x["label"] == 1)
    .shuffle(seed=42)
    .select(range(15))
)

test_data = concatenate_datasets([
    test_negative,
    test_positive
]).shuffle(seed=42)

print("Train:", len(train_data))
print("Validation:", len(test_data))

from transformers import AutoTokenizer
from transformers import AutoModelForSequenceClassification

model_name = "distilbert-base-uncased"

tokenizer = AutoTokenizer.from_pretrained(model_name)

model = AutoModelForSequenceClassification.from_pretrained(
    model_name,
    num_labels=2,
    id2label={0: "Negative", 1: "Positive"},
    label2id={"Negative": 0, "Positive": 1}
)

print("Loaded:", model_name)

def tokenize(batch):
    return tokenizer(
        batch["text"],
        truncation=True,
        padding="max_length",
        max_length=64
    )

train_data = train_data.map(tokenize, batched=True)
test_data = test_data.map(tokenize, batched=True)

print("Input IDs:")
print(train_data[0]["input_ids"][:20])

print("\nAttention Mask:")
print(train_data[0]["attention_mask"][:20])

sentence = "This movie is amazing!"

tokens = tokenizer.tokenize(sentence)
ids = tokenizer.encode(sentence)

print("Sentence:", sentence)
print("Tokens:", tokens)
print("Token IDs:", ids)
print("Decoded:", tokenizer.decode(ids))

from transformers import TrainingArguments

training_args = TrainingArguments(
    output_dir="./distilbert-demo",
    num_train_epochs=1,
    per_device_train_batch_size=4,
    per_device_eval_batch_size=4,
    learning_rate=2e-5,
    eval_strategy="epoch",
    save_strategy="no",
    logging_steps=5,
    report_to="none",
    fp16=False,
    dataloader_num_workers=0
)

print("Training configuration ready!")

from transformers import Trainer
from sklearn.metrics import accuracy_score

def compute_metrics(eval_pred):
    logits, labels = eval_pred
    predictions = logits.argmax(axis=-1)

    return {
        "accuracy": accuracy_score(labels, predictions)
    }

trainer = Trainer(
    model=model,
    args=training_args,
    train_dataset=train_data,
    eval_dataset=test_data,
    compute_metrics=compute_metrics
)

print("Trainer ready!")

import time

start = time.time()

trainer.train()

elapsed = time.time() - start

print(f"Training time: {elapsed:.2f} seconds")
print(f"Training time: {elapsed / 60:.2f} minutes")

results = trainer.evaluate()

print("Validation Loss:", results["eval_loss"])
print("Validation Accuracy:", results["eval_accuracy"])

import matplotlib.pyplot as plt

logs = trainer.state.log_history

steps = [x["step"] for x in logs if "loss" in x]
losses = [x["loss"] for x in logs if "loss" in x]

plt.figure(figsize=(8, 4))
plt.plot(steps, losses, marker="o")

plt.xlabel("Training Step")
plt.ylabel("Loss")
plt.title("DistilBERT Fine-tuning Loss")
plt.grid(True)
plt.show()

def predict_sentiment(text):
    inputs = tokenizer(
        text,
        return_tensors="pt",
        truncation=True,
        max_length=64
    )

    inputs = {
        key: value.to(model.device)
        for key, value in inputs.items()
    }

    model.eval()

    with torch.no_grad():
        outputs = model(**inputs)
        probabilities = torch.softmax(outputs.logits, dim=-1)

    predicted_class = probabilities.argmax(dim=-1).item()
    confidence = probabilities[0, predicted_class].item()

    print("Text:", text)
    print("Prediction:", model.config.id2label[predicted_class])
    print("Softmax score:", f"{confidence:.2%}")
    print("-" * 40)


predict_sentiment("This movie is amazing!")
predict_sentiment("I hate this movie!")
predict_sentiment("The acting was terrible.")
predict_sentiment("I really enjoyed this film.")

save_path = "./my-distilbert"

trainer.save_model(save_path)
tokenizer.save_pretrained(save_path)

print("Model saved:", save_path)

